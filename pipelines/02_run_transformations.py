"""
02_run_transformations.py
=========================
Transforms bronze landing tables into the gold unified marketing performance mart.

Execution paths (auto-detected):
  First run  (gold table absent):  3 quarantine MERGEs + CREATE OR REPLACE TABLE
                                   gold — all SQL generated by SqlBuilder.
  Incremental (gold table exists): 3 quarantine MERGEs (separate jobs) +
                                   3 gold MERGEs inside a single BEGIN/COMMIT
                                   transaction for atomicity.

Infrastructure bootstrap (runs before any BQ operation):
  _ensure_infrastructure() creates the three BigQuery datasets and the two
  metadata tables (audit + quarantine) with explicit schemas and DAY
  partitioning if they do not already exist.  Idempotent; safe to run every
  time.  Solves the "dataset not found" 404 on first deployment.

Quality guarantees (LLD §3):
  - OOP; single-responsibility classes; no global mutable state
  - Retry with exponential backoff (2s, 4s, 8s) on all BQ operations
  - AuditLogger: append-only ledger (no DML UPDATE; no string-escaping bugs)
  - Post-write verification: column count==30, row counts, spend reconciliation
  - maximum_bytes_billed on QueryJobConfig ONLY (never LoadJobConfig)
  - Logs to stdout + logs/02_run_transformations.log
  - sys.exit(1) on unrecoverable failure
"""

