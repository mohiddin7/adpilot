_RETRYABLE = (InternalServerError, ServiceUnavailable, DeadlineExceeded)


class BQExecutor:
    """Executes BigQuery jobs with retry and cost guardrails. No business logic."""

    def __init__(self, client: bigquery.Client, log: logging.Logger) -> None:
        self._client = client
        self._log    = log

    def run_query(
        self, sql: str, max_bytes: int, description: str = "query",
    ) -> bigquery.QueryJob:
        cfg = bigquery.QueryJobConfig(
            maximum_bytes_billed=max_bytes, use_legacy_sql=False,
        )
        last_exc: Exception | None = None
        for attempt in range(1, Config.MAX_RETRIES + 1):
            try:
                job = self._client.query(sql, job_config=cfg)
                job.result()
                gb = (job.total_bytes_processed or 0) / 1_024 ** 3
                self._log.debug("[%s] OK  %.4f GB (attempt %d)", description, gb, attempt)
                return job
            except _RETRYABLE as exc:
                last_exc = exc
                if attempt < Config.MAX_RETRIES:
                    wait = Config.RETRY_BASE_S ** attempt
                    self._log.warning(
                        "[%s] Transient %s (attempt %d/%d) — retry in %ds",
                        description, type(exc).__name__, attempt, Config.MAX_RETRIES, wait,
                    )
                    time.sleep(wait)
                else:
                    self._log.error("[%s] Exhausted %d retries. Last: %s",
                                    description, Config.MAX_RETRIES, exc)
            except BadRequest as exc:
                self._log.error("[%s] BadRequest (non-retryable): %s", description, exc)
                raise
        raise RuntimeError(
            f"[{description}] Failed after {Config.MAX_RETRIES} attempts. Last: {last_exc}"
        ) from last_exc

    def load_rows(
        self,
        rows: list[dict[str, Any]],
        destination: str,
        job_config: bigquery.LoadJobConfig,
        description: str = "load",
    ) -> bigquery.LoadJob:
        """
        Batch-load via LoadJob — NO streaming buffer.
        Never use insert_rows_json: streaming buffer blocks UPDATE for ~90 min.
        LoadJobConfig does NOT accept maximum_bytes_billed (verified).
        """
        last_exc: Exception | None = None
        for attempt in range(1, Config.MAX_RETRIES + 1):
            try:
                job = self._client.load_table_from_json(rows, destination, job_config=job_config)
                job.result()
                self._log.debug("[%s] Load OK  %d row(s) (attempt %d)",
                                description, len(rows), attempt)
                return job
            except _RETRYABLE as exc:
                last_exc = exc
                if attempt < Config.MAX_RETRIES:
                    wait = Config.RETRY_BASE_S ** attempt
                    self._log.warning("[%s] Transient load error (attempt %d/%d) — retry in %ds",
                                      description, attempt, Config.MAX_RETRIES, wait)
                    time.sleep(wait)
            except Exception as exc:
                self._log.error("[%s] Load error: %s", description, exc)
                raise
        raise RuntimeError(
            f"[{description}] Load failed after {Config.MAX_RETRIES} attempts."
        ) from last_exc

    def table_exists(self, full_table_id: str) -> bool:
        try:
            self._client.get_table(full_table_id)
            return True
        except NotFound:
            return False



# =============================================================================
# AuditLogger  —  Append-Only Ledger Pattern
# =============================================================================
# Design decision (replaces UPDATE-based pattern):
#
#   WHY: tbl_ingestion_audit is unpartitioned. Every UPDATE DML scans the whole
#   table.  As the table grows past Config.AUDIT_MAX_BYTES (10 MB), the UPDATE
#   for the FAILED state exceeds the cost guardrail and throws BadRequest —
#   blinding the monitoring system at the exact moment you need it most.
#   Additionally, the previous _sql_literal helper's manual string escaping
#   ('replace single-quotes with backslash-single-quote') generates invalid BQ
#   SQL when error messages contain apostrophes, producing the "Unclosed string
#   literal" crash seen in production.
#
#   FIX: Every lifecycle event writes a NEW ROW via load_table_from_json.
#   No DML UPDATE ever runs.  No string escaping needed.  JSON handles all
#   special characters correctly.
#
#   Downstream reporting (latest status per run):
#     SELECT * EXCEPT (rn)
#     FROM (
#       SELECT *, ROW_NUMBER() OVER (
#           PARTITION BY audit_id ORDER BY last_updated_at DESC) AS rn
#       FROM `{STAGING_DS}.tbl_ingestion_audit`
#     ) WHERE rn = 1
# =============================================================================

class AuditLogger:
    """
    Append-only event log for one pipeline run.
    Each status change inserts a fresh row; no UPDATEs are issued.
    """

    def __init__(self, executor: BQExecutor, log: logging.Logger) -> None:
        self._ex         = executor
        self._log        = log
        self.audit_id    = str(uuid.uuid4())
        self._started_at: str = ""
        self._bronze_rows: int = 0

    # ── Public phase methods ─────────────────────────────────────────────────

    def started(self, bronze_row_count: int) -> None:
        self._started_at  = datetime.now(timezone.utc).isoformat()
        self._bronze_rows = bronze_row_count
        self._insert_event(status="STARTED")
        self._log.info("Audit row inserted  audit_id=%s  bronze_rows=%d",
                       self.audit_id, bronze_row_count)

    def transforming(self, mode: str) -> None:
        """mode: 'FIRST_RUN' or 'INCREMENTAL'"""
        self._insert_event(status=f"TRANSFORMING_{mode}")

    def verifying(self) -> None:
        self._insert_event(status="VERIFYING")

    def success(self, rows_accepted: int, rows_quarantined: int) -> None:
        self._insert_event(
            status="SUCCESS",
            rows_accepted=rows_accepted,
            rows_quarantined=rows_quarantined,
            rows_merged=rows_accepted,
            completed_at=datetime.now(timezone.utc).isoformat(),
        )

    def failed(self, error_message: str, error_stage: str) -> None:
        # No string escaping needed — load_table_from_json uses JSON serialization
        self._insert_event(
            status="FAILED",
            error_message=error_message[:4_096],
            error_stage=error_stage,
            completed_at=datetime.now(timezone.utc).isoformat(),
        )

    # ── Internal ─────────────────────────────────────────────────────────────

    def _insert_event(self, **override_fields: Any) -> None:
        """Insert one audit event row; all special characters safe via JSON."""
        row: dict[str, Any] = {
            "audit_id":         self.audit_id,
            "file_name":        "gold_transformation",
            "file_size_bytes":  None,
            "platform":         "all",
            "started_at":       self._started_at,
            "last_updated_at":  datetime.now(timezone.utc).isoformat(),
            "completed_at":     None,
            "rows_in_file":     self._bronze_rows,
            "rows_accepted":    None,
            "rows_quarantined": None,
            "rows_merged":      None,
            "status":           "UNKNOWN",
            "error_message":    None,
            "error_stage":      None,
        }
        row.update(override_fields)
        self._ex.load_rows(
            rows=[row],
            destination=Config.audit_ref(),
            job_config=bigquery.LoadJobConfig(
                source_format=bigquery.SourceFormat.NEWLINE_DELIMITED_JSON,
                write_disposition=bigquery.WriteDisposition.WRITE_APPEND,
            ),
            description=f"audit:{row['status']}",
        )


