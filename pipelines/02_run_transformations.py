class GoldTransformer:
    """
    Orchestrates the gold transformation.  Detects first-run vs. incremental,
    runs the appropriate path, verifies, and keeps the audit in sync.
    """

    def __init__(self, client: bigquery.Client, log: logging.Logger, window: Window = None) -> None:
        self._client   = client
        self._log      = log
        self._window   = window
        self._ex       = BQExecutor(client, log)
        self._audit    = AuditLogger(self._ex, log)
        self._sql      = SqlBuilder
        self._verifier = Verifier(self._ex, log)

    def run(self) -> None:
        # ── Phase 0: Infrastructure bootstrap ─────────────────────────────────
        # Must run BEFORE any audit logging because the audit table itself
        # might not exist yet.  If this fails, we raise immediately — no
        # attempt to write to the audit table (it may not be there).
        try:
            self._ensure_infrastructure()
        except Exception as exc:
            self._log.critical(
                "Infrastructure bootstrap FAILED — cannot proceed. "
                "Audit logging unavailable at this point. Error: %s", exc,
            )
            raise

        # ── Phase 1–N: Normal pipeline flow ───────────────────────────────────
        error_stage = "INIT"
        try:
            error_stage = "COUNT_BRONZE"
            bronze_rows = self._count_bronze_rows()

            self._audit.started(bronze_rows)

            error_stage = "DETECT_MODE"
            gold_exists = self._ex.table_exists(Config.gold_ref())
            mode = "INCREMENTAL" if gold_exists else "FIRST_RUN"
            self._log.info("Execution mode: %s  (gold table %s)",
                           mode, "EXISTS" if gold_exists else "ABSENT")
            self._audit.transforming(mode)

            error_stage = f"TRANSFORM_{mode}"
            if gold_exists:
                self._run_incremental()
            else:
                self._run_first_run()

            error_stage = "VERIFY"
            self._audit.verifying()
            # ponytail: verification reconciles all of bronze vs gold, O(history) bytes but
            # under BigQuery's 10 MB per-query minimum for ~a decade; bound it to self._window
            # once a query bills above the minimum
            gold_counts, rows_quarantined = self._run_verification(bronze_rows)
            rows_accepted = sum(gold_counts.values())

            self._audit.success(rows_accepted, rows_quarantined)
            self._log.info(
                "Script 02 COMPLETE  mode=%s  gold_rows=%d  quarantined=%d",
                mode, rows_accepted, rows_quarantined,
            )

        except Exception as exc:
            msg = str(exc)
            self._log.error("FAILED at stage=%s: %s", error_stage, msg)
            try:
                # Append-only audit: no string escaping risk, no cost guardrail hit
                self._audit.failed(msg, error_stage)
            except Exception as audit_exc:
                self._log.error("Also failed to write FAILED audit event: %s", audit_exc)
            raise

    # ── Infrastructure bootstrap ──────────────────────────────────────────────

    def _ensure_infrastructure(self) -> None:
        """
        Idempotent infrastructure bootstrap.  Creates the three BigQuery
        datasets and the two metadata tables (audit + quarantine) with
        explicit schemas and DAY partitioning if they do not already exist.

        Design decisions:
          • Uses client.create_dataset(exists_ok=True) — single API call;
            no pre-flight get_dataset needed.
          • Datasets are created in Config.BQ_LOCATION ("US") to match the
            existing bronze tables (confirmed by the 404 error location hint).
          • Audit and quarantine tables are created with explicit SchemaField
            lists rather than relying on JSON auto-detection — ensures correct
            types (e.g., TIMESTAMP vs STRING) and DAY partitioning with
            90-day expiry that auto-detect cannot set.
          • Gold mart table is NOT created here — SqlBuilder.create_gold_schema()
            handles it with the correct PARTITION + CLUSTER DDL.
        """
        self._log.info("Infrastructure: verifying / creating BQ resources ...")

        # ── 1. Datasets ────────────────────────────────────────────────────
        for ds_id in [Config.BRONZE_DS, Config.STAGING_DS, Config.PRODUCTION_DS]:
            ds_obj = bigquery.Dataset(f"{Config.PROJECT}.{ds_id}")
            ds_obj.location = Config.BQ_LOCATION
            self._client.create_dataset(ds_obj, exists_ok=True)
            self._log.info("  dataset OK: %s", ds_id)

        # ── 2. Audit table ─────────────────────────────────────────────────
        # Append-only ledger; QUALIFY ROW_NUMBER() view gives latest status.
        # Partitioned on started_at so UPDATE-style queries (if ever added)
        # scan only one day's partition.
        _AUDIT_SCHEMA = [
            bigquery.SchemaField("audit_id",         "STRING",    mode="REQUIRED"),
            bigquery.SchemaField("file_name",         "STRING"),
            bigquery.SchemaField("file_size_bytes",   "INT64"),
            bigquery.SchemaField("platform",          "STRING"),
            bigquery.SchemaField("started_at",        "TIMESTAMP", mode="REQUIRED"),
            bigquery.SchemaField("last_updated_at",   "TIMESTAMP", mode="REQUIRED"),
            bigquery.SchemaField("completed_at",      "TIMESTAMP"),
            bigquery.SchemaField("rows_in_file",      "INT64"),
            bigquery.SchemaField("rows_accepted",     "INT64"),
            bigquery.SchemaField("rows_quarantined",  "INT64"),
            bigquery.SchemaField("rows_merged",       "INT64"),
            bigquery.SchemaField("status",            "STRING",    mode="REQUIRED"),
            bigquery.SchemaField("error_message",     "STRING"),
            bigquery.SchemaField("error_stage",       "STRING"),
        ]
        audit_tbl = bigquery.Table(Config.audit_ref(), schema=_AUDIT_SCHEMA)
        audit_tbl.time_partitioning = bigquery.TimePartitioning(
            field="started_at",
            expiration_ms=90 * 24 * 3_600 * 1_000,   # 90-day auto-expiry (LLD §10.4)
        )
        self._client.create_table(audit_tbl, exists_ok=True)
        self._log.info("  table OK: %s", Config.AUDIT_TABLE)

        # ── 3. Quarantine table ────────────────────────────────────────────
        # WRITE_APPEND via quarantine MERGE; MD5 quarantine_id prevents dups.
        _QUARANTINE_SCHEMA = [
            bigquery.SchemaField("quarantine_id",            "STRING",    mode="REQUIRED"),
            bigquery.SchemaField("execution_timestamp",      "TIMESTAMP", mode="REQUIRED"),
            bigquery.SchemaField("origin_platform",          "STRING"),
            bigquery.SchemaField("raw_record_json",          "STRING"),
            bigquery.SchemaField("violated_rule_identifier", "STRING"),
            bigquery.SchemaField("remediation_status",       "STRING"),
        ]
        q_tbl = bigquery.Table(Config.quarantine_ref(), schema=_QUARANTINE_SCHEMA)
        q_tbl.time_partitioning = bigquery.TimePartitioning(
            field="execution_timestamp",
            expiration_ms=90 * 24 * 3_600 * 1_000,
        )
        self._client.create_table(q_tbl, exists_ok=True)
        self._log.info("  table OK: %s", Config.QUARANTINE_TABLE)

        self._log.info("Infrastructure: all resources verified ✓")

    # ── First-run path ────────────────────────────────────────────────────────

    def _run_first_run(self) -> None:
        """
        First-run: 5 BigQuery jobs.

        1-3: Quarantine MERGEs per platform (idempotent, route bad rows out).
        4:   CREATE TABLE IF NOT EXISTS — creates the empty gold table with
             the full NOT NULL schema contract.  DDL only; no data scanned.
        5:   incremental_transaction() — the same BEGIN/COMMIT MERGE transaction
             used on every incremental run.  On an empty table every row is
             WHEN NOT MATCHED → INSERT.  Subsequent runs UPDATE or INSERT.

        Why this is better than the old CREATE OR REPLACE TABLE ... AS SELECT:
          • CREATE OR REPLACE destroys NOT NULL constraints and column
            descriptions every time it runs (BigQuery infers schema from SELECT
            and cannot preserve metadata defined in a prior DDL).
          • CREATE TABLE IF NOT EXISTS preserves the schema contract forever.
          • First-run and incremental now share the same MERGE logic — no two
            separate code paths that can drift out of sync.
        """
        platforms = list(self._sql._PLATFORM_CONFIG.keys())

        if self._window is not None:
            self._log.info("First run: window ignored, building all of history")

        for platform in platforms:
            self._log.info("First-run: quarantine MERGE — %s", platform)
            self._ex.run_query(
                self._sql.quarantine_merge(platform),
                max_bytes=Config.QUARANTINE_MERGE_MAX_BYTES,
                description=f"first_run:quarantine:{platform}",
            )

        self._log.info(
            "First-run: CREATE TABLE IF NOT EXISTS — %d cols (%d NOT NULL, 6 nullable derived)",
            len(self._sql._GOLD_COLUMN_SPEC),
            sum(1 for *_, not_null, _ in self._sql._GOLD_COLUMN_SPEC if not_null),
        )
        # DDL — no data scanned; use VERIFY_MAX_BYTES as a safe non-zero cap
        self._ex.run_query(
            self._sql.create_gold_schema(),
            max_bytes=Config.VERIFY_MAX_BYTES,
            description="first_run:create_gold_schema",
        )

        self._log.info("First-run: populate gold via MERGE transaction")
        self._ex.run_query(
            self._sql.incremental_transaction(),
            max_bytes=Config.GOLD_TXN_MAX_BYTES,
            description="first_run:gold_merge_transaction",
        )
        self._log.info("First-run complete — gold table created with NOT NULL schema and populated")

    # ── Incremental path ──────────────────────────────────────────────────────

    def _run_incremental(self) -> None:
        """
        Incremental: 2 phases.

        Phase 1 — Quarantine MERGEs (outside transaction; idempotent):
          Each run in its own job.  MD5 primary key prevents double-quarantine.

        Phase 2 — Gold MERGEs (inside BEGIN/COMMIT transaction):
          All 3 platforms in one atomic multi-statement job.
          If TikTok's MERGE fails after Facebook+Google succeed, BigQuery
          rolls back the entire transaction — no partial-platform state.
        """
        platforms = list(self._sql._PLATFORM_CONFIG.keys())

        self._log.info("Incremental: window %s", self._window)

        # Phase 1: quarantine MERGEs
        for platform in platforms:
            self._log.info("Incremental: quarantine MERGE — %s", platform)
            q_job = self._ex.run_query(
                self._sql.quarantine_merge(platform, self._window),
                max_bytes=Config.QUARANTINE_MERGE_MAX_BYTES,
                description=f"incremental:quarantine:{platform}",
            )
            inserted = (q_job.dml_stats.inserted_row_count or 0)
            self._log.info("  quarantine inserted: %d", inserted)

        # Phase 2: gold MERGEs in a single transaction
        self._log.info("Incremental: BEGIN gold MERGEs transaction (3 platforms)")
        self._ex.run_query(
            self._sql.incremental_transaction(self._window),
            max_bytes=Config.GOLD_TXN_MAX_BYTES,
            description="incremental:gold_transaction",
        )
        self._log.info("Incremental: gold MERGEs COMMITTED")

    # ── Verification ──────────────────────────────────────────────────────────

    def _run_verification(
        self, bronze_rows: int
    ) -> tuple[dict[str, int], int]:
        """
        Returns (gold_row_counts_by_platform, total_quarantined_rows).
        Raises on column-count mismatch (Data Contract violation).
        """
        col_ok = self._verifier.verify_column_count()
        if not col_ok:
            raise RuntimeError(
                f"Data Contract violated: gold table column count != "
                f"{Config.EXPECTED_GOLD_COLS}."
            )
        gold_counts = self._verifier.verify_row_counts()
        self._verifier.verify_financial_reconciliation()
        quarantined = max(bronze_rows - sum(gold_counts.values()), 0)
        return gold_counts, quarantined

    def _count_bronze_rows(self) -> int:
        job  = self._ex.run_query(
            self._sql.bronze_total_rows_query(),
            max_bytes=Config.VERIFY_MAX_BYTES,
            description="count:bronze_total",
        )
        rows = list(job.result())
        return int(rows[0].total_rows) if rows else 0


