    @classmethod
    def create_gold_schema(cls) -> str:
        """
        CREATE TABLE IF NOT EXISTS with explicit NOT NULL constraints and
        column descriptions.

        Design rationale (replaces CREATE OR REPLACE TABLE ... AS SELECT):
          • CREATE OR REPLACE infers schema from the SELECT — BigQuery drops
            every NOT NULL constraint and OPTIONS(description) in the process.
          • CREATE TABLE IF NOT EXISTS with explicit column definitions preserves
            the schema contract on every run.
          • The table is populated separately via incremental_transaction() —
            the same MERGE that runs on every incremental update.  First-run
            and incremental are now identical in execution logic.
          • NOT NULL on all 24 base columns is safe because every metric column
            uses COALESCE(SAFE_CAST(...), 0) or CAST(0 AS TYPE) in the L1
            select — zero is always produced, never NULL.
          • The 6 SAFE_DIVIDE derived metrics stay NULLABLE because a zero
            denominator legitimately produces NULL (e.g. campaign with no
            conversions → cpa IS NULL, which is correct — NOT zero).
        """
        gold = Config.gold_ref()
        col_lines = []
        for name, bq_type, not_null, desc in cls._GOLD_COLUMN_SPEC:
            null_clause = " NOT NULL" if not_null else "        "
            col_lines.append(
                f"  {name:<26} {bq_type:<8}{null_clause}"
                f"  OPTIONS(description=\"{desc}\")"
            )
        col_block = ",\n".join(col_lines)
        return (
            f"CREATE TABLE IF NOT EXISTS `{gold}`\n"
            f"(\n{col_block}\n)\n"
            f"PARTITION BY date\n"
            f"CLUSTER BY platform, campaign_id"
        )

    @classmethod
    def incremental_transaction(cls, window: Window = None) -> str:
        """
        Wrap all 3 gold MERGEs in a BigQuery transaction.
        Atomicity: if TikTok MERGE fails after Facebook+Google commit,
        the whole transaction rolls back — no partial-platform state.
        DDL is not allowed inside BigQuery transactions; only DML (MERGE) here.
        """
        stmts = "\n".join(cls.gold_merge(p, window) + ";" for p in cls._PLATFORM_CONFIG)
        return f"BEGIN TRANSACTION;\n{stmts}\nCOMMIT TRANSACTION;"

    @classmethod
    def bronze_total_rows_query(cls) -> str:
        """Total row count across all three bronze tables for the audit log."""
        parts = " +\n    ".join(
            f"(SELECT COUNT(*) FROM `{Config.bronze_ref(pspec['bronze_table'])}`)"
            for pspec in cls._PLATFORM_CONFIG.values()
        )
        return f"SELECT\n    {parts} AS total_rows"

