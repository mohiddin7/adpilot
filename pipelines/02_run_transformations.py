class Verifier:
    """
    Post-execution verification.  Runs after transformation completes.
    Critical failures: sys.exit(1) via caller.
    Warning failures: logged but do not abort.
    """

    def __init__(self, executor: BQExecutor, log: logging.Logger) -> None:
        self._ex  = executor
        self._log = log

    def verify_column_count(self) -> bool:
        """
        Data Contract: gold table must have exactly 30 columns.
        Uses INFORMATION_SCHEMA (no table scan — just metadata).
        """
        sql = f"""
        SELECT COUNT(*) AS col_count
        FROM   `{Config.PROJECT}.{Config.PRODUCTION_DS}.INFORMATION_SCHEMA.COLUMNS`
        WHERE  table_name = '{Config.GOLD_TABLE}'
        """
        job  = self._ex.run_query(sql, Config.VERIFY_MAX_BYTES, "verify:col_count")
        rows = list(job.result())
        col_count = rows[0].col_count if rows else 0
        passed = (col_count == Config.EXPECTED_GOLD_COLS)
        if passed:
            self._log.info("Column count OK: %d (expected %d)",
                           col_count, Config.EXPECTED_GOLD_COLS)
        else:
            self._log.error(
                "COLUMN COUNT MISMATCH: got %d, expected %d  "
                "(Data Contract violation — check transformation SQL)",
                col_count, Config.EXPECTED_GOLD_COLS,
            )
        return passed

    def verify_row_counts(self) -> dict[str, int]:
        """
        Returns per-platform row counts in gold table.
        Also returns bronze counts for comparison.  Logs warning if mismatched
        (expected when quarantine > 0; failure-worthy only if gold has MORE rows
        than bronze — would indicate a bug).
        """
        gold_sql = f"""
        SELECT platform, COUNT(*) AS cnt
        FROM   `{Config.gold_ref()}`
        GROUP  BY platform
        ORDER  BY platform
        """
        bronze_sql = f"""
        SELECT 'Facebook' AS platform,
               COUNT(*) AS cnt
        FROM   `{Config.bronze_ref('facebook_ads_landing')}`
        UNION ALL
        SELECT 'Google', COUNT(*)
        FROM   `{Config.bronze_ref('google_ads_landing')}`
        UNION ALL
        SELECT 'TikTok', COUNT(*)
        FROM   `{Config.bronze_ref('tiktok_ads_landing')}`
        """
        gold_job   = self._ex.run_query(gold_sql,   Config.VERIFY_MAX_BYTES, "verify:gold_rows")
        bronze_job = self._ex.run_query(bronze_sql, Config.VERIFY_MAX_BYTES, "verify:bronze_rows")

        gold_counts   = {r.platform: r.cnt for r in gold_job.result()}
        bronze_counts = {r.platform: r.cnt for r in bronze_job.result()}

        total_gold   = sum(gold_counts.values())
        total_bronze = sum(bronze_counts.values())

        for platform in sorted(bronze_counts):
            g = gold_counts.get(platform, 0)
            b = bronze_counts[platform]
            quarantined = b - g
            if quarantined < 0:
                self._log.error(
                    "Row count BUG: gold has MORE rows than bronze for %s "
                    "(gold=%d, bronze=%d) — investigate MERGE key collision",
                    platform, g, b,
                )
            elif quarantined > 0:
                self._log.warning(
                    "Row count: %s  gold=%d  bronze=%d  quarantined=%d (G1-G12 violations)",
                    platform, g, b, quarantined,
                )
            else:
                self._log.info("Row count OK: %s  gold=%d == bronze=%d",
                               platform, g, b)

        self._log.info(
            "Total rows — gold: %d  bronze: %d  quarantined: %d",
            total_gold, total_bronze, total_bronze - total_gold,
        )
        return gold_counts

    def verify_financial_reconciliation(self) -> bool:
        """
        Per-platform: |bronze_spend - gold_spend| <= SPEND_TOLERANCE ($0.01).
        With clean data (0 quarantined rows) this should be exact.
        Mismatch > tolerance on a non-quarantine run indicates a bug.
        """
        bronze_sql = f"""
        SELECT 'Facebook' AS platform,
               SUM(COALESCE(SAFE_CAST(NULLIF(spend, '') AS FLOAT64), 0)) AS spend
        FROM   `{Config.bronze_ref('facebook_ads_landing')}`
        UNION ALL
        SELECT 'Google',
               SUM(COALESCE(SAFE_CAST(NULLIF(cost, '') AS FLOAT64), 0))
        FROM   `{Config.bronze_ref('google_ads_landing')}`
        UNION ALL
        SELECT 'TikTok',
               SUM(COALESCE(SAFE_CAST(NULLIF(cost, '') AS FLOAT64), 0))
        FROM   `{Config.bronze_ref('tiktok_ads_landing')}`
        """
        gold_sql = f"""
        SELECT platform, SUM(spend) AS spend
        FROM   `{Config.gold_ref()}`
        GROUP  BY platform
        ORDER  BY platform
        """
        b_job = self._ex.run_query(bronze_sql, Config.VERIFY_MAX_BYTES, "verify:bronze_spend")
        g_job = self._ex.run_query(gold_sql,   Config.VERIFY_MAX_BYTES, "verify:gold_spend")

        bronze_spend = {r.platform: r.spend for r in b_job.result()}
        gold_spend   = {r.platform: r.spend for r in g_job.result()}

        all_passed = True
        for platform in sorted(bronze_spend):
            b = bronze_spend[platform]
            g = gold_spend.get(platform, 0.0) or 0.0
            diff = abs(b - g)
            if diff <= Config.SPEND_TOLERANCE:
                self._log.info(
                    "Spend reconciliation OK: %s  bronze=$%.2f  gold=$%.2f  diff=$%.4f",
                    platform, b, g, diff,
                )
            else:
                self._log.error(
                    "SPEND MISMATCH: %s  bronze=$%.2f  gold=$%.2f  diff=$%.4f  "
                    "(tolerance=$%.2f) — quarantine or CAST error?",
                    platform, b, g, diff, Config.SPEND_TOLERANCE,
                )
                all_passed = False

        total_gold = sum(gold_spend.values())
        self._log.info("Total gold spend: $%.2f  (LLD ground truth: $%.2f)",
                       total_gold, 130_244.90)
        return all_passed



